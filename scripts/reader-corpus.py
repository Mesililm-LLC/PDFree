"""Generate only the three public reader-tool fixtures and update their manifest entries."""
from pathlib import Path
import hashlib
import json
import sys

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / ".tools" / "python"))
from pypdf import PdfWriter

out = root / "tests" / "corpus"
writer = PdfWriter()
writer.add_blank_page(width=612, height=792)
writer.write(out / "blank.pdf")
writer = PdfWriter(clone_from=out / "text.pdf")
writer.encrypt("pdfree-test", owner_password="pdfree-owner-test", permissions_flag=0, algorithm="RC4-128")
writer.write(out / "restricted-copy.pdf")
writer = PdfWriter(clone_from=out / "text.pdf")
writer.pages[0].cropbox.lower_left = (40, 20)
writer.pages[0].cropbox.upper_right = (572, 772)
writer.write(out / "crop-origin.pdf")
manifest_path = out / "manifest.json"
manifest = {entry["file"]: entry for entry in json.loads(manifest_path.read_text(encoding="utf-8"))}
for name in ("blank.pdf", "restricted-copy.pdf", "crop-origin.pdf"):
    path = out / name
    manifest[name] = {"file": name, "sha256": hashlib.sha256(path.read_bytes()).hexdigest(), "bytes": path.stat().st_size,
        "provenance": "Original PDFree fixture generated by scripts/reader-corpus.py with pypdf 6.1.1",
        "license": "AGPL-3.0-only", "pages": 1, "encrypted": name == "restricted-copy.pdf", "embedded_fonts": False}
manifest_path.write_text(json.dumps(list(manifest.values()), indent=2) + "\n", encoding="utf-8")
