"""Owned navigation fixture; no user documents are read or modified."""
from pathlib import Path
import hashlib
import json
import sys
root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / ".tools" / "python"))
from pypdf import PdfWriter
from pypdf.annotations import Link
from pypdf.generic import DictionaryObject, NameObject, DecodedStreamObject
writer = PdfWriter()
font=writer._add_object(DictionaryObject({NameObject('/Type'):NameObject('/Font'),NameObject('/Subtype'):NameObject('/Type1'),NameObject('/BaseFont'):NameObject('/Helvetica')}))
for index in range(3):
    page=writer.add_blank_page(width=612, height=792)
    page[NameObject('/Resources')]=DictionaryObject({NameObject('/Font'):DictionaryObject({NameObject('/F1'):font})})
    stream=DecodedStreamObject()
    stream.set_data(f'BT /F1 18 Tf 60 700 Td (PDFree navigation page {index+1}) Tj ET'.encode())
    page[NameObject('/Contents')]=writer._add_object(stream)
parent = writer.add_outline_item("First chapter", 0)
writer.add_outline_item("Second page", 1, parent=parent)
writer.add_outline_item("Third page", 2)
writer.add_annotation(0, Link(rect=(50, 600, 200, 640), target_page_index=1))
writer.add_annotation(0, Link(rect=(50, 500, 200, 540), url="https://example.org/pdfree"))
writer.add_annotation(0, Link(rect=(50, 400, 200, 440), url="file:///C:/unsafe.pdf"))
writer.pages[1].cropbox.lower_left = (40, 20)
writer.pages[1].cropbox.upper_right = (572, 772)
writer.add_annotation(1, Link(rect=(50, 600, 200, 640), target_page_index=2))
path = root / "tests/corpus/navigation.pdf"
writer.write(path)
manifest_path = root / "tests/corpus/manifest.json"
manifest = {e["file"]: e for e in json.loads(manifest_path.read_text())}
manifest[path.name] = {"file": path.name, "sha256": hashlib.sha256(path.read_bytes()).hexdigest(), "bytes": path.stat().st_size, "provenance": "Original PDFree navigation fixture generated by scripts/navigation-corpus.py with pypdf 6.1.1", "license": "AGPL-3.0-only", "pages": 3, "encrypted": False, "embedded_fonts": False}
manifest_path.write_text(json.dumps(list(manifest.values()), indent=2) + "\n")
